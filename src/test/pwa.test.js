import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * PWA / offline support.
 *
 * These are file-level assertions rather than render tests: the manifest, the
 * worker and the icon files are build artefacts, and the thing that actually
 * goes wrong with a PWA is a stale reference or a missing file that nobody
 * notices until a user tries to install the app.
 */

const root = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const at = (...parts) => join(root, ...parts);

const read = (...parts) => readFileSync(at(...parts), 'utf8');
const exists = (...parts) => existsSync(at(...parts));

/** Read a PNG's IHDR dimensions without an image library. */
function pngSize(file) {
  const buf = readFileSync(file);
  expect(buf.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a');
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

describe('web app manifest', () => {
  const manifestPath = 'public/manifest.webmanifest';

  it('exists', () => {
    expect(exists(manifestPath)).toBe(true);
  });

  it('is valid JSON', () => {
    expect(() => JSON.parse(read(manifestPath))).not.toThrow();
  });

  it('has every key a browser needs to offer installation', () => {
    const m = JSON.parse(read(manifestPath));
    expect(m.name).toBe('Precision Resume Studio');
    expect(m.short_name).toBe('Resume Studio');
    expect(m.start_url).toBe('/');
    expect(m.display).toBe('standalone');
    expect(m.theme_color.toLowerCase()).toBe('#140715');
    expect(m.background_color.toLowerCase()).toBe('#140715');
    expect(Array.isArray(m.icons)).toBe(true);
  });

  it('declares 192 and 512 icons, both present on disk at the declared size', () => {
    const { icons } = JSON.parse(read(manifestPath));
    const declared = icons.map((i) => i.sizes);
    expect(declared).toContain('192x192');
    expect(declared).toContain('512x512');

    for (const icon of icons) {
      const rel = icon.src.replace(/^\//, '');
      expect(exists('public', rel), `missing icon file: ${icon.src}`).toBe(true);
      expect(icon.type).toBe('image/png');

      const [w, h] = icon.sizes.split('x').map(Number);
      const actual = pngSize(at('public', rel));
      // A mislabelled icon is the classic PWA failure: the manifest says 512
      // and the file is 192, so Android renders a blurry upscale.
      expect(actual, `size mismatch for ${icon.src}`).toEqual({ width: w, height: h });
    }
  });

  it('ships a maskable icon so Android does not letterbox it', () => {
    const { icons } = JSON.parse(read(manifestPath));
    expect(icons.some((i) => (i.purpose || '').includes('maskable'))).toBe(true);
  });
});

describe('icons', () => {
  it('are generated by a committed script, not hand-placed', () => {
    expect(exists('scripts/make-icons.mjs')).toBe(true);
  });

  it('the generator writes both sizes', () => {
    const src = read('scripts/make-icons.mjs');
    expect(src).toContain('192');
    expect(src).toContain('512');
    expect(src).toContain('public');
  });

  it('are small enough to precache', () => {
    for (const file of ['public/icons/icon-192.png', 'public/icons/icon-512.png']) {
      expect(statSync(at(file)).size).toBeLessThan(64 * 1024);
    }
  });
});

describe('index.html', () => {
  const html = read('index.html');

  it('links the manifest', () => {
    expect(html).toMatch(/<link[^>]+rel=["']manifest["'][^>]*>/);
    expect(html).toContain('/manifest.webmanifest');
  });

  it('declares a matching theme colour', () => {
    expect(html).toContain('name="theme-color"');
    expect(html).toContain('#140715');
  });

  it('provides an apple touch icon for iOS, which ignores the manifest icons', () => {
    expect(html).toContain('rel="apple-touch-icon"');
    expect(html).toContain('/icons/icon-192.png');
  });
});

describe('service worker source', () => {
  const sw = read('src/sw.js');

  it('uses a versioned cache name', () => {
    expect(sw).toContain('__CACHE_VERSION__');
    expect(sw).toMatch(/CACHE_NAME\s*=\s*`\$\{CACHE_PREFIX\}-\$\{CACHE_VERSION\}`/);
  });

  it('deletes caches from previous versions on activate', () => {
    expect(sw).toContain("addEventListener('activate'");
    expect(sw).toContain('caches.keys()');
    expect(sw).toContain('caches.delete');
    expect(sw).toContain('name !== CACHE_NAME');
  });

  it('is network-first for the shell and cache-first for assets', () => {
    expect(sw).toContain('networkFirstShell');
    expect(sw).toContain('cacheFirst');
    // The shell path must try the network before the cache.
    const shellFn = sw.slice(sw.indexOf('async function networkFirstShell'));
    expect(shellFn.indexOf('await fetch(request)')).toBeLessThan(shellFn.indexOf('cache.match'));
  });

  it('never intercepts the job agent on :3457', () => {
    expect(sw).toContain('3457');
    expect(sw).toContain('AGENT_PORT');
    // The bypass runs before any respondWith.
    expect(sw.indexOf('isBypassed(request, url)')).toBeLessThan(sw.indexOf('respondWith'));
  });

  it('never caches cross-origin requests', () => {
    expect(sw).toContain('url.origin !== self.location.origin');
  });

  it('only caches same-origin basic responses, so opaque ones cannot poison it', () => {
    expect(sw).toContain("response.type === 'basic'");
  });

  it('does not throw during install when a precache URL is unavailable', () => {
    // allSettled, not all: one 404 must not abort the whole install.
    expect(sw).toContain('Promise.allSettled');
  });

  it('has an offline fallback page rather than letting the browser show its own', () => {
    expect(sw).toMatch(/You are offline/);
  });
});

describe('registration', () => {
  const main = read('src/main.jsx');

  it('is guarded on production', () => {
    expect(main).toContain('import.meta.env.PROD');
    expect(main).toMatch(/import\.meta\.env\.PROD\s*&&/);
  });

  it('is a no-op without service worker support', () => {
    expect(main).toContain("'serviceWorker' in navigator");
  });

  it('swallows a failed registration so a missing worker cannot break the app', () => {
    expect(main).toMatch(/\.register\(['"]\/sw\.js['"]\)\s*\.catch/);
  });

  it('does not import the worker source into the app bundle', () => {
    // src/sw.js is copied verbatim at build time; importing it would make Vite
    // bundle it as a module and break the placeholders.
    expect(main).not.toContain("from './sw.js'");
    expect(main).not.toContain('src/sw.js');
  });
});

describe('build wiring', () => {
  const config = read('vite.config.js');

  it('emits the worker from a build hook without a plugin dependency', () => {
    expect(config).toContain('closeBundle');
    expect(config).toContain('src/sw.js');
    // No PWA plugin: the project avoids a dependency for what a small script does.
    expect(config).not.toContain('vite-plugin-pwa');
  });

  it('substitutes both placeholders', () => {
    expect(config).toContain('__PRECACHE_MANIFEST__');
    expect(config).toContain('__CACHE_VERSION__');
  });

  it('build-static verifies the PWA artefacts instead of assuming', () => {
    const bs = read('scripts/build-static.mjs');
    expect(bs).toContain('manifest.webmanifest');
    expect(bs).toContain('sw.js');
    expect(bs).toContain('icons/icon-192.png');
  });
});
